-- ============================================================
-- 1. TABLAS MAESTRAS
-- ============================================================

-- 1.1 CATEGORIA_EQUIPO
CREATE TABLE Categoria_Equipo (
    id_categoria     NUMBER(6) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_categoria VARCHAR2(60) NOT NULL UNIQUE,
    descripcion      VARCHAR2(200)
);

-- 1.2 PROVEEDOR
CREATE TABLE Proveedor (
    id_proveedor  NUMBER(6) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ruc           VARCHAR2(15) NOT NULL UNIQUE,
    razon_social  VARCHAR2(100) NOT NULL,
    telefono      VARCHAR2(15),
    email         VARCHAR2(100),
    direccion     VARCHAR2(150)
);

-- 1.3 SERVICIO
CREATE TABLE Servicio (
    id_servicio NUMBER(6) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR2(60) NOT NULL UNIQUE,
    descripcion VARCHAR2(200),
    precio_base NUMBER(10,2) NOT NULL
);

-- 1.4 PAQUETE_SERVICIO  (combos: internet + cable, etc.)
CREATE TABLE Paquete_Servicio (
    id_paquete  NUMBER(6) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR2(80) NOT NULL UNIQUE,
    descripcion VARCHAR2(200),
    precio      NUMBER(10,2) NOT NULL
);

-- 1.5 DETALLE_PAQUETE  (N:M entre Paquete y Servicio)
CREATE TABLE Detalle_Paquete (
    id_paquete  NUMBER(6) NOT NULL,
    id_servicio NUMBER(6) NOT NULL,
    PRIMARY KEY (id_paquete, id_servicio),
    FOREIGN KEY (id_paquete)  REFERENCES Paquete_Servicio(id_paquete),
    FOREIGN KEY (id_servicio) REFERENCES Servicio(id_servicio)
);

-- 1.6 CLIENTE
CREATE TABLE Cliente (
    id_cliente    NUMBER(6) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nro_documento VARCHAR2(15) NOT NULL UNIQUE,
    nombres       VARCHAR2(80) NOT NULL,
    apellidos     VARCHAR2(80) NOT NULL,
    direccion     VARCHAR2(150) NOT NULL,
    telefono      VARCHAR2(15),
    email         VARCHAR2(100),
    tipo_cliente  VARCHAR2(20) NOT NULL
);

-- 1.7 ESPECIALIDAD
CREATE TABLE Especialidad (
    id_especialidad NUMBER(6) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR2(60) NOT NULL UNIQUE,
    descripcion     VARCHAR2(150)
);

-- 1.8 TECNICO
CREATE TABLE Tecnico (
    id_tecnico    NUMBER(6) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nro_documento VARCHAR2(15) NOT NULL UNIQUE,
    nombres       VARCHAR2(80) NOT NULL,
    apellidos     VARCHAR2(80) NOT NULL,
    telefono      VARCHAR2(15),
    estado        VARCHAR2(15) DEFAULT 'Activo' NOT NULL
);

-- 1.9 TECNICO_ESPECIALIDAD  (N:M entre Técnico y Especialidad)
CREATE TABLE Tecnico_Especialidad (
    id_tecnico      NUMBER(6) NOT NULL,
    id_especialidad NUMBER(6) NOT NULL,
    PRIMARY KEY (id_tecnico, id_especialidad),
    FOREIGN KEY (id_tecnico)      REFERENCES Tecnico(id_tecnico),
    FOREIGN KEY (id_especialidad) REFERENCES Especialidad(id_especialidad)
);

-- ============================================================
-- 2. TABLAS TRANSACCIONALES
-- ============================================================

-- 2.1 ORDEN_INSTALACION
CREATE TABLE Orden_Instalacion (
    id_orden         NUMBER(8) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente       NUMBER(6) NOT NULL,
    id_tecnico       NUMBER(6) NOT NULL,
    fecha_registro   DATE DEFAULT SYSDATE NOT NULL,
    fecha_programada DATE NOT NULL,
    fecha_ejecucion  DATE,
    estado           VARCHAR2(15) DEFAULT 'Pendiente' NOT NULL,
    prioridad        VARCHAR2(10) DEFAULT 'Normal' NOT NULL,
    costo_total      NUMBER(10,2) DEFAULT 0,
    observaciones    VARCHAR2(250),
    FOREIGN KEY (id_cliente) REFERENCES Cliente(id_cliente),
    FOREIGN KEY (id_tecnico) REFERENCES Tecnico(id_tecnico)
);

-- 2.2 DETALLE_ORDEN
CREATE TABLE Detalle_Orden (
    id_detalle  NUMBER(8) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden    NUMBER(8) NOT NULL,
    id_servicio NUMBER(6),
    id_paquete  NUMBER(6),
    cantidad    NUMBER(4) DEFAULT 1 NOT NULL,
    precio_unit NUMBER(10,2) NOT NULL,
    FOREIGN KEY (id_orden)    REFERENCES Orden_Instalacion(id_orden),
    FOREIGN KEY (id_servicio) REFERENCES Servicio(id_servicio),
    FOREIGN KEY (id_paquete)  REFERENCES Paquete_Servicio(id_paquete)
);

-- ============================================================
-- 3. TABLAS DE INVENTARIO
-- ============================================================

-- 3.1 EQUIPO (modelo del producto, sin serial)
CREATE TABLE Equipo (
    id_equipo         NUMBER(8) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre            VARCHAR2(80) NOT NULL,
    id_categoria      NUMBER(6) NOT NULL,
    marca             VARCHAR2(60),
    modelo            VARCHAR2(60),
    stock_minimo      NUMBER(6) DEFAULT 0 NOT NULL,
    precio_referencia NUMBER(10,2),
    FOREIGN KEY (id_categoria) REFERENCES Categoria_Equipo(id_categoria)
);

-- 3.2 EQUIPO_SERIAL (una fila por unidad física)
CREATE TABLE Equipo_Serial (
    id_serial    NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_equipo    NUMBER(8) NOT NULL,
    codigo_serial VARCHAR2(40) NOT NULL UNIQUE,
    estado       VARCHAR2(20) DEFAULT 'Disponible' NOT NULL,
    fecha_ingreso DATE DEFAULT SYSDATE NOT NULL,
    FOREIGN KEY (id_equipo) REFERENCES Equipo(id_equipo)
);

-- 3.3 COMPRA_INVENTARIO (cabecera)
CREATE TABLE Compra_Inventario (
    id_compra    NUMBER(8) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proveedor NUMBER(6) NOT NULL,
    fecha_compra DATE DEFAULT SYSDATE NOT NULL,
    total        NUMBER(10,2) DEFAULT 0,
    FOREIGN KEY (id_proveedor) REFERENCES Proveedor(id_proveedor)
);

-- 3.4 DETALLE_COMPRA
CREATE TABLE Detalle_Compra (
    id_detalle_compra NUMBER(8) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_compra         NUMBER(8) NOT NULL,
    id_equipo         NUMBER(8) NOT NULL,
    cantidad          NUMBER(6) NOT NULL,
    precio_unit       NUMBER(10,2) NOT NULL,
    FOREIGN KEY (id_compra) REFERENCES Compra_Inventario(id_compra),
    FOREIGN KEY (id_equipo) REFERENCES Equipo(id_equipo)
);

-- 3.5 CONSUMO_EQUIPO
CREATE TABLE Consumo_Equipo (
    id_consumo    NUMBER(8) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden      NUMBER(8) NOT NULL,
    id_equipo     NUMBER(8) NOT NULL,
    cantidad      NUMBER(4) NOT NULL,
    fecha_consumo DATE DEFAULT SYSDATE NOT NULL,
    FOREIGN KEY (id_orden)  REFERENCES Orden_Instalacion(id_orden),
    FOREIGN KEY (id_equipo) REFERENCES Equipo(id_equipo)
);

-- 3.6 MOVIMIENTO_INVENTARIO (trazabilidad de stock)
CREATE TABLE Movimiento_Inventario (
    id_movimiento NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_equipo     NUMBER(8) NOT NULL,
    tipo          VARCHAR2(10) NOT NULL,
    cantidad      NUMBER(6) NOT NULL,
    fecha         DATE DEFAULT SYSDATE NOT NULL,
    motivo        VARCHAR2(150),
    id_orden      NUMBER(8),
    id_compra     NUMBER(8),
    FOREIGN KEY (id_equipo) REFERENCES Equipo(id_equipo),
    FOREIGN KEY (id_orden)  REFERENCES Orden_Instalacion(id_orden),
    FOREIGN KEY (id_compra) REFERENCES Compra_Inventario(id_compra)
);

