-- 5.1 TRIGGER: al insertar consumo, descuenta stock y registra movimiento
CREATE OR REPLACE TRIGGER trg_consumo_stock
AFTER INSERT ON Consumo_Equipo
FOR EACH ROW
BEGIN
    INSERT INTO Movimiento_Inventario (id_equipo, tipo, cantidad, motivo, id_orden)
    VALUES (:NEW.id_equipo, 'Salida', :NEW.cantidad, 'Consumo en orden', :NEW.id_orden);

    UPDATE Equipo_Serial
       SET estado = 'Instalado'
     WHERE id_equipo = :NEW.id_equipo
       AND estado = 'Disponible'
       AND ROWNUM <= :NEW.cantidad;
END;
/

-- 5.2 TRIGGER: al registrar compra, genera entrada en inventario
CREATE OR REPLACE TRIGGER trg_compra_entrada
AFTER INSERT ON Detalle_Compra
FOR EACH ROW
BEGIN
    INSERT INTO Movimiento_Inventario (id_equipo, tipo, cantidad, motivo, id_compra)
    VALUES (:NEW.id_equipo, 'Entrada', :NEW.cantidad, 'Compra a proveedor', :NEW.id_compra);
END;
/

-- 5.3 PROCEDIMIENTO: registrar orden completa
CREATE OR REPLACE PROCEDURE sp_registrar_orden (
    p_id_cliente  IN NUMBER,
    p_id_tecnico  IN NUMBER,
    p_fecha       IN DATE,
    p_id_servicio IN NUMBER,
    p_precio      IN NUMBER
) AS
    v_id_orden NUMBER;
BEGIN
    INSERT INTO Orden_Instalacion (id_cliente, id_tecnico, fecha_programada, estado)
    VALUES (p_id_cliente, p_id_tecnico, p_fecha, 'Pendiente');

    SELECT MAX(id_orden) INTO v_id_orden FROM Orden_Instalacion;

    INSERT INTO Detalle_Orden (id_orden, id_servicio, cantidad, precio_unit)
    VALUES (v_id_orden, p_id_servicio, 1, p_precio);

    UPDATE Orden_Instalacion
       SET costo_total = p_precio
     WHERE id_orden = v_id_orden;

    COMMIT;
END;
/

-- 5.4 PROCEDIMIENTO: registrar compra de inventario
CREATE OR REPLACE PROCEDURE sp_registrar_compra (
    p_id_proveedor IN NUMBER,
    p_id_equipo    IN NUMBER,
    p_cantidad     IN NUMBER,
    p_precio       IN NUMBER
) AS
    v_id_compra NUMBER;
BEGIN
    INSERT INTO Compra_Inventario (id_proveedor, total)
    VALUES (p_id_proveedor, p_cantidad * p_precio);

    SELECT MAX(id_compra) INTO v_id_compra FROM Compra_Inventario;

    INSERT INTO Detalle_Compra (id_compra, id_equipo, cantidad, precio_unit)
    VALUES (v_id_compra, p_id_equipo, p_cantidad, p_precio);

    COMMIT;
END;
/

-- 5.5 FUNCIÓN: stock disponible por categoría
CREATE OR REPLACE FUNCTION fn_stock_categoria (p_id_categoria IN NUMBER)
RETURN NUMBER
IS
    v_total NUMBER;
BEGIN
    SELECT NVL(COUNT(*), 0) INTO v_total
    FROM Equipo_Serial es
    JOIN Equipo e ON e.id_equipo = es.id_equipo
    WHERE e.id_categoria = p_id_categoria
      AND es.estado = 'Disponible';
    RETURN v_total;
END;
/

-- 5.6 FUNCIÓN: costo total de una orden
CREATE OR REPLACE FUNCTION fn_costo_orden (p_id_orden IN NUMBER)
RETURN NUMBER
IS
    v_total NUMBER;
BEGIN
    SELECT NVL(SUM(cantidad * precio_unit), 0) INTO v_total
    FROM Detalle_Orden
    WHERE id_orden = p_id_orden;
    RETURN v_total;
END;
/

-- 5.7 CURSOR: equipos con stock crítico (bajo mínimo)
DECLARE
    CURSOR cur_stock_critico IS
        SELECT e.nombre, e.stock_minimo, COUNT(es.id_serial) AS disponibles
        FROM Equipo e
        LEFT JOIN Equipo_Serial es
               ON es.id_equipo = e.id_equipo
              AND es.estado = 'Disponible'
        GROUP BY e.nombre, e.stock_minimo
        HAVING COUNT(es.id_serial) <= e.stock_minimo;

    v_nombre VARCHAR2(80);
    v_min    NUMBER(6);
    v_disp   NUMBER(6);
BEGIN
    OPEN cur_stock_critico;
    LOOP
        FETCH cur_stock_critico INTO v_nombre, v_min, v_disp;
        EXIT WHEN cur_stock_critico%NOTFOUND;
        INSERT INTO Movimiento_Inventario (id_equipo, tipo, cantidad, motivo)
        SELECT id_equipo, 'Ajuste', 0, 'Stock crítico: ' || v_nombre || ' (' || v_disp || '/' || v_min || ')'
        FROM Equipo WHERE nombre = v_nombre;
    END LOOP;
    CLOSE cur_stock_critico;
    COMMIT;
END;
/

-- 5.8 CURSOR: carga de trabajo por técnico
DECLARE
    CURSOR cur_carga IS
        SELECT t.nombres || ' ' || t.apellidos AS tecnico, COUNT(o.id_orden) AS total
        FROM Tecnico t
        LEFT JOIN Orden_Instalacion o ON o.id_tecnico = t.id_tecnico
        GROUP BY t.nombres, t.apellidos;

    v_tecnico VARCHAR2(160);
    v_total   NUMBER;
BEGIN
    OPEN cur_carga;
    LOOP
        FETCH cur_carga INTO v_tecnico, v_total;
        EXIT WHEN cur_carga%NOTFOUND;
        -- Solo se procesa si tiene más de 0 órdenes
        IF v_total > 0 THEN
            NULL; -- aquí podría registrarse en otra tabla de resumen
        END IF;
    END LOOP;
    CLOSE cur_carga;
END;
/

