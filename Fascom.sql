CREATE OR REPLACE VIEW vw_stock_critico AS
SELECT e.nombre AS equipo,
       c.nombre_categoria AS categoria,
       e.stock_minimo,
       COUNT(es.id_serial) AS disponibles
FROM Equipo e
JOIN Categoria_Equipo c ON c.id_categoria = e.id_categoria
LEFT JOIN Equipo_Serial es
       ON es.id_equipo = e.id_equipo
      AND es.estado = 'Disponible'
GROUP BY e.nombre, c.nombre_categoria, e.stock_minimo
HAVING COUNT(es.id_serial) <= e.stock_minimo;

CREATE OR REPLACE VIEW vw_ordenes_por_estado AS
SELECT estado, COUNT(*) AS total
FROM Orden_Instalacion
GROUP BY estado;

CREATE OR REPLACE VIEW vw_ingresos_por_mes AS
SELECT TO_CHAR(fecha_registro,'YYYY-MM') AS mes,
       SUM(costo_total) AS ingresos
FROM Orden_Instalacion
WHERE estado = 'Completada'
GROUP BY TO_CHAR(fecha_registro,'YYYY-MM');

CREATE OR REPLACE VIEW vw_equipos_instalados AS
SELECT c.nombres || ' ' || c.apellidos AS cliente,
       o.id_orden,
       e.nombre AS equipo,
       ce.cantidad
FROM Consumo_Equipo ce
JOIN Orden_Instalacion o ON o.id_orden = ce.id_orden
JOIN Cliente c          ON c.id_cliente = o.id_cliente
JOIN Equipo e           ON e.id_equipo = ce.id_equipo;

